/**
 * Build-time generator for
 * `src/renderer/src/word/templateNoTocBytes.ts` — the NO table of
 * contents variant of the BDB Word template.
 *
 * Why this exists
 * ---------------
 * The Word export can render with or without a table of contents.
 * "With" uses `Molio 2_Skabelon BDB.docx` (5 Word sections, incl. the
 * front-matter TOC). "Without" uses `Molio 2_Skabelon BDB_NoTOC.docx`
 * — the same template with the TOC (and its front-matter section
 * break) removed, so it has 4 Word sections. The renderer needs both
 * templates' bytes at runtime; the simplest way to ship them is a
 * pre-built TypeScript module with the bytes as base64. Same trick as
 * `build-bdb-template.mjs`.
 *
 * Run when
 * --------
 *   - Whenever the no-TOC template file at the source path below is
 *     updated by Tore. Keep it in sync with the with-TOC template
 *     (`build-bdb-template.mjs`): a change to one should usually be
 *     mirrored in the other.
 *
 * Usage
 * -----
 *   node packages/app/scripts/build-bdb-template-notoc.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(__dirname, "..");
const REPO_ROOT = resolve(PACKAGE_ROOT, "..", "..");

const TEMPLATE_PATH = join(
  REPO_ROOT,
  "0900 Examples",
  "Basics + Work_areas",
  "Molio 2_Skabelon BDB_NoTOC.docx",
);
const OUT_PATH = join(
  PACKAGE_ROOT,
  "src",
  "renderer",
  "src",
  "word",
  "templateNoTocBytes.ts",
);

console.log("Reading no-TOC template from", TEMPLATE_PATH);
const bytes = readFileSync(TEMPLATE_PATH);
const b64 = bytes.toString("base64");
console.log(
  `Template size: ${bytes.length} bytes (${b64.length} base64 chars)`,
);

const out = `/**
 * BDB Word-export template bytes — NO table of contents variant.
 * Generated by \`scripts/build-bdb-template-notoc.mjs\`.
 *
 * Source: \`0900 Examples/Basics + Work_areas/Molio 2_Skabelon BDB_NoTOC.docx\`.
 * Same template as \`templateBytes.ts\` but with the table of contents
 * (and its front-matter section break) removed, so it has 4 Word
 * sections instead of 5. Used when exporting with the table of
 * contents turned OFF. See \`buildBdbDocx.ts\` for the 4-section path.
 *
 * Regenerate by running
 *   \`node packages/app/scripts/build-bdb-template-notoc.mjs\`
 * from the repo root after Tore updates the no-TOC template file.
 */

/* eslint-disable */

const BASE64 = "${b64}";

let cached: Uint8Array | null = null;

export function getBdbTemplateNoTocBytes(): Uint8Array {
  if (cached == null) {
    const binStr = atob(BASE64);
    const out = new Uint8Array(binStr.length);
    for (let i = 0; i < binStr.length; i++) {
      out[i] = binStr.charCodeAt(i);
    }
    cached = out;
  }
  return new Uint8Array(cached);
}
`;

writeFileSync(OUT_PATH, out);
console.log("Wrote", OUT_PATH);
