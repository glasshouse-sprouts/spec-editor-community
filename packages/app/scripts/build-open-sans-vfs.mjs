/**
 * Build-time generator for `src/renderer/src/pdf/openSansVfs.ts`.
 *
 * Why this exists
 * ---------------
 * pdfmake needs font bytes as base64 strings inside its `vfs` object
 * (a virtual file-system map keyed by filename). Bundling the four
 * `.ttf` files for Open Sans (Regular / Italic / Bold / BoldItalic)
 * as a pre-generated TypeScript module gives us a synchronous
 * import — same shape as pdfmake's bundled Roboto VFS — and avoids
 * any runtime fetch/await dance during PDF export.
 *
 * Run when
 * --------
 *   - First time the app is set up after a fresh `npm install`.
 *   - After upgrading `@expo-google-fonts/open-sans` to pick up new
 *     font hinting / glyph fixes.
 *
 * Usage
 * -----
 *   node packages/app/scripts/build-open-sans-vfs.mjs
 *
 * Produces `packages/app/src/renderer/src/pdf/openSansVfs.ts`
 * (~700 KB). Commit the output — we want the file in source so
 * dev-mode startups don't require running this first.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(__dirname, "..");
const REPO_ROOT = resolve(PACKAGE_ROOT, "..", "..");
const FONTS_DIR = join(
  REPO_ROOT,
  "node_modules",
  "@expo-google-fonts",
  "open-sans",
);
const OUT_PATH = join(
  PACKAGE_ROOT,
  "src",
  "renderer",
  "src",
  "pdf",
  "openSansVfs.ts",
);

const SOURCES = {
  "OpenSans-Regular.ttf": join(
    FONTS_DIR,
    "400Regular",
    "OpenSans_400Regular.ttf",
  ),
  "OpenSans-Italic.ttf": join(
    FONTS_DIR,
    "400Regular_Italic",
    "OpenSans_400Regular_Italic.ttf",
  ),
  "OpenSans-Bold.ttf": join(FONTS_DIR, "700Bold", "OpenSans_700Bold.ttf"),
  "OpenSans-BoldItalic.ttf": join(
    FONTS_DIR,
    "700Bold_Italic",
    "OpenSans_700Bold_Italic.ttf",
  ),
};

console.log("Reading TTFs from", FONTS_DIR);
const entries = [];
for (const [vfsName, path] of Object.entries(SOURCES)) {
  const b64 = readFileSync(path).toString("base64");
  entries.push(`  "${vfsName}": "${b64}"`);
  console.log(`  ${vfsName}: ${b64.length} base64 chars`);
}

const header = `/**
 * Open Sans VFS for pdfmake — generated by
 * \`scripts/build-open-sans-vfs.mjs\`.
 *
 * One source of truth for the four font-weight TTF files we embed
 * into every PDF the app produces (FONT slice, 2026-05-12). The
 * payload is base64-encoded TTF bytes; pdfmake reads it out of
 * \`pdfMake.vfs[<name>]\` whenever it needs to lay out a glyph in
 * one of the four registered styles.
 *
 * Why pre-built rather than runtime-fetch:
 *   - Synchronous import keeps the PDF builders pure (no async
 *     bootstrap required before the first export).
 *   - Tests can import this file the same way they import the
 *     Roboto fallback (\`pdfmake/build/vfs_fonts.js\`); no jsdom
 *     fetch shim needed.
 *   - File size (~700 KB base64 for four weights) is comparable
 *     to the bundled Roboto VFS, so we're not adding a new
 *     installer-size concern.
 *
 * Regenerate by running
 *   \`node packages/app/scripts/build-open-sans-vfs.mjs\`
 * from the repo root after upgrading \`@expo-google-fonts/open-sans\`.
 */

/* eslint-disable */

export const OPEN_SANS_VFS: Record<string, string> = {
`;

const footer = `
};

/** Pdfmake font-family mapping. Pass this in each builder's doc
 *  definition under \`fonts\` so pdfmake knows which VFS file to use
 *  for each style. */
export const OPEN_SANS_FONT_MAP = {
  OpenSans: {
    normal: "OpenSans-Regular.ttf",
    bold: "OpenSans-Bold.ttf",
    italics: "OpenSans-Italic.ttf",
    bolditalics: "OpenSans-BoldItalic.ttf",
  },
} as const;
`;

writeFileSync(OUT_PATH, header + entries.join(",\n") + footer);
console.log("Wrote", OUT_PATH);
